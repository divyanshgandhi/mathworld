// Writes docs/levelling-proof.md from the simulation. Run: bun run proof
import { writeFileSync } from "node:fs";
import { BOTS } from "../sim/bots";
import { measure, SEEDS } from "../sim/proof";

const PLANET = ["Earth", "Moon", "Mars", "Asteroid Belt", "Jupiter", "Saturn", "Uranus", "Deep Space"];
const { claims, runs } = measure();
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const at = (bot: string, q: number) => {
  const c: number[] = Array(8).fill(0);
  for (const r of runs[bot]) c[r.tierAt(q)]++;
  return c.map((n, t) => (n ? `${PLANET[t]} ${Math.round((n / runs[bot].length) * 100)}%` : "")).filter(Boolean).join(", ");
};

const lines = [
  "# Levelling proof",
  "",
  `_Generated by \`bun run proof\` from \`sim/\`. ${SEEDS} seeded runs per bot, 30 questions each, played through the real \`src/director/fold.ts\` and \`src/director/next.ts\`. The same claims are asserted in \`tests/levelling.test.ts\`._`,
  "",
  "## Claims",
  "",
  "| Bot | Claim | Measured | Required |",
  "|---|---|---|---|",
  ...claims.map((c) => `| ${c.bot} | ${c.claim} | **${pct(c.rate)}** | ≥ ${pct(c.min)} |`),
  "",
  "## Where each bot is after 10, 15 and 30 questions",
  "",
  "| Bot | Q10 | Q15 | Q30 |",
  "|---|---|---|---|",
  ...Object.keys(BOTS).map((b) => `| ${b} | ${at(b, 10)} | ${at(b, 15)} | ${at(b, 30)} |`),
  "",
  "## The bots",
  "",
  "- **struggling-3rd-grader**: knows ×0, ×1, ×2, ×5 and ×10 by heart (95%, fast). Everything else: 20% on a first try, slow.",
  "- **average-5th-grader**: all single-digit facts by heart. 2-digit × 1-digit: 30% on a first try (80% on round numbers like 6 × 20).",
  "- **adult-speedrunner**: 97% right and fast at every tier.",
  "- **random-masher**: types random numbers within a fraction of a second and often ignores the Radar.",
  "- **trick-learner**: careful (right but never fast) on everything except the hard ×9 facts (15%). Show Me How teaches it the trick for good.",
  "",
  "## Rules the harness tested, and two it changed",
  "",
  "1. **A Hyper-Jump must not skip the planet where the gap is.**",
  "   - With \"3 Golds in a row → jump 2 planets\", the struggler (fluent on the Moon) jumped straight over Mars, the planet it cannot do. The same happened to the 5th-grader, over Jupiter.",
  "   - Now, after two Golds the next wave is a **probe** from the planet that would be skipped. Only a third, Gold probe earns the jump.",
  "   - The adult still reaches multi-digit within 10 questions.",
  "2. **Clearing a planet counts the cadet's own first-try answers.** A mission is the anchor warm-up plus 4 in-tier waves, and it clears on 3 of the 4. Earth is the exception: 2 of 3 tutorial waves.",
  "   - Power-Ups count, because they are a conceptual win.",
  "   - Radar picks and Show Me How do not.",
  "   - Counting any wave solved without Show Me How (the spec's wording) let lucky Radar picks walk a struggling cadet off their frontier.",
  "",
  "## One trajectory per bot (seed 1000)",
  "",
  ...Object.keys(BOTS).flatMap((b) => {
    const r = runs[b][0];
    return [`**${b}**`, "", "```", ...r.steps.map((s) => `${String(s.q).padStart(2)}  ${PLANET[s.wave.tier].padEnd(13)} ${s.wave.role.padEnd(11)} ${`${s.wave.a} × ${s.wave.b}`.padEnd(12)} ${s.outcome.padEnd(14)} → ${PLANET[s.tierAfter]}`), "```", ""];
  }),
];
writeFileSync("docs/levelling-proof.md", lines.join("\n"));
const failed = claims.filter((c) => c.rate < c.min);
console.log(`docs/levelling-proof.md written; ${claims.length - failed.length}/${claims.length} claims hold.`);
if (failed.length) process.exit(1);
